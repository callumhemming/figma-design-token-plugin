// Writes .vscode/tokens.preview.css: the :root tokens from
// src/styles/tokens.css with every var() alias resolved to its final value.
// The CSS Variable Autocomplete extension reads this (see
// .vscode/settings.json) so alias tokens show their real colour in
// autocomplete and hover -- it only resolves aliases for its inline swatches.
// Run as part of `npm run build:tokens`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const SOURCE = fileURLToPath(new URL("../src/styles/tokens.css", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../.vscode/tokens.preview.css", import.meta.url));

const root = postcss.parse(readFileSync(SOURCE, "utf8"));

// Only the default context (light theme, acme brand) -- the dark/globex
// blocks redefine the same names, and the extension keeps one value per name.
const tokens = new Map();
root.walkRules(":root", (rule) => {
  rule.walkDecls(/^--/, (decl) => tokens.set(decl.prop, decl.value));
});

const VAR = /var\(\s*(--[\w-]+)\s*(?:,\s*([^()]*(?:\([^()]*\))*[^()]*))?\)/g;

function resolve(value, seen = new Set()) {
  return value.replace(VAR, (match, name, fallback) => {
    if (seen.has(name)) return match;
    const next = tokens.get(name) ?? fallback;
    return next === undefined ? match : resolve(next, new Set(seen).add(name));
  });
}

const lines = [...tokens].map(([name, value]) => {
  const resolved = resolve(value);
  const alias = value.match(/^var\(\s*(--[\w-]+)\s*\)$/)?.[1];
  const comment = alias ? `  /* alias of ${alias} */\n` : "";
  return `${comment}  ${name}: ${resolved};`;
});

writeFileSync(
  OUTPUT,
  `/* Autogenerated by scripts/build-token-preview.mjs -- editor preview only,
 * not used by the app. Aliases are resolved to their light/acme value. */

:root {
${lines.join("\n")}
}
`,
);
console.log(`Wrote ${tokens.size} tokens to .vscode/tokens.preview.css`);
